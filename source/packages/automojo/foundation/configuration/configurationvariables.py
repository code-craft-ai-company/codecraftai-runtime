import os

from automojo.foundation.startup.startupvariables import (
    AM_STARTUP_VARIABLES,
    resolve_startup_variables
)

from automojo.foundation.collections.wellknown import ContextSingleton
from automojo.foundation.collections.contextpaths import ContextPaths
from automojo.foundation.collections.mergemap import MergeMap


from automojo.foundation.configuration.normalize import (
    split_and_normalize_name_list,
    split_and_normalize_path_list,
    split_and_normalize_source_list
)

from automojo.foundation.configuration.configurationsettings import AM_CONFIG_DEFAULTS


class CONFIGURATION_MAPS:
    CREDENTIAL_CONFIGURATION_MAP = MergeMap()
    LANDSCAPE_CONFIGURATION_MAP = MergeMap()
    RUNTIME_CONFIGURATION_MAP = MergeMap(AM_CONFIG_DEFAULTS.DEFAULT_CONFIGURATION)
    TOPOLOGY_CONFIGURATION_MAP = MergeMap()


class AM_CONFIG_VARNAMES:

    AM_NAME = "AM_NAME"

    AM_HOME_DIRECTORY = "AM_HOME_DIRECTORY"

    AM_CONFIG_DIRECTORY = "AM_CONFIG_DIRECTORY"

    AM_CONFIG_PASS_PHRASE = "AM_CONFIG_PASS_PHRASE"

    AM_CONFIG_STORAGE_URI = "AM_CONFIG_STORAGE_URI"

    AM_CONFIG_CREDENTIAL_NAMES = "AM_CONFIG_CREDENTIAL_NAMES"
    AM_CONFIG_CREDENTIAL_URIS = "AM_CONFIG_CREDENTIAL_URIS"
    AM_CONFIG_CREDENTIAL_SOURCES = "AM_CONFIG_CREDENTIAL_SOURCES"
    AM_CONFIG_CREDENTIAL_FILES = "AM_CONFIG_CREDENTIAL_FILES"

    AM_CONFIG_LANDSCAPE_NAMES = "AM_CONFIG_LANDSCAPE_NAMES"
    AM_CONFIG_LANDSCAPE_URIS = "AM_CONFIG_LANDSCAPE_URIS"
    AM_CONFIG_LANDSCAPE_SOURCES = "AM_CONFIG_LANDSCAPE_SOURCES"
    AM_CONFIG_LANDSCAPE_FILES = "AM_CONFIG_LANDSCAPE_FILES"

    AM_CONFIG_TOPOLOGY_NAMES = "AM_CONFIG_TOPOLOGY_NAMES"
    AM_CONFIG_TOPOLOGY_URIS = "AM_CONFIG_TOPOLOGY_URIS"
    AM_CONFIG_TOPOLOGY_SOURCES = "AM_CONFIG_TOPOLOGY_SOURCES"
    AM_CONFIG_TOPOLOGY_FILES = "AM_CONFIG_TOPOLOGY_FILES"

    AM_CONFIG_RUNTIME_NAMES = "AM_CONFIG_RUNTIME_NAMES"
    AM_CONFIG_RUNTIME_URIS = "AM_CONFIG_RUNTIME_URIS"
    AM_CONFIG_RUNTIME_SOURCES = "AM_CONFIG_RUNTIME_SOURCES"
    AM_CONFIG_RUNTIME_FILES = "AM_CONFIG_RUNTIME_FILES"


class AM_CONFIG_VARIABLES(AM_STARTUP_VARIABLES):

    AM_CONFIG_REQUIRE_CREDENTIALS = AM_CONFIG_DEFAULTS.AM_CONFIG_REQUIRE_CREDENTIALS
    AM_CONFIG_REQUIRE_LANDSCAPE = AM_CONFIG_DEFAULTS.AM_CONFIG_REQUIRE_LANDSCAPE
    AM_CONFIG_REQUIRE_RUNTIME = AM_CONFIG_DEFAULTS.AM_CONFIG_REQUIRE_RUNTIME
    AM_CONFIG_REQUIRE_TOPOLOGY = AM_CONFIG_DEFAULTS.AM_CONFIG_REQUIRE_TOPOLOGY

    AM_CONFIG_STORAGE_URI = AM_CONFIG_DEFAULTS.AM_CONFIG_STORAGE_URI

    AM_CONFIG_USE_CREDENTIALS = False
    AM_CONFIG_USE_LANDSCAPE = False
    AM_CONFIG_USE_RUNTIME = False
    AM_CONFIG_USE_TOPOLOGY = False

    AM_CONFIG_DIRECTORY = None

    AM_CONFIG_PASS_PHRASE = None

    AM_CONFIG_CREDENTIAL_NAMES = None
    AM_CONFIG_CREDENTIAL_URIS = None
    AM_CONFIG_CREDENTIAL_SOURCES = None
    AM_CONFIG_CREDENTIAL_FILES = None

    AM_CONFIG_LANDSCAPE_NAMES = None
    AM_CONFIG_LANDSCAPE_URIS = None
    AM_CONFIG_LANDSCAPE_SOURCES = None
    AM_CONFIG_LANDSCAPE_FILES = None

    AM_CONFIG_TOPOLOGY_NAMES = None
    AM_CONFIG_TOPOLOGY_URIS = None
    AM_CONFIG_TOPOLOGY_SOURCES = None
    AM_CONFIG_TOPOLOGY_FILES = None

    AM_CONFIG_RUNTIME_NAMES = None
    AM_CONFIG_RUNTIME_URIS = None
    AM_CONFIG_RUNTIME_SOURCES = None
    AM_CONFIG_RUNTIME_FILES = None


def resolve_configuration_variables():

    # We need to resolve extension variables because we are
    # dependent on some of them.
    resolve_startup_variables()

    environ = os.environ

    ctx = ContextSingleton()

    # For now, we don't want to put the CREDENTIALS CONFIGURATION into the context, because at the moment we don't 
    # want to pass it around in the plain.  Possibly what we can do is create a version of MergeMap that will serialize
    # with a protective pass key or something like that.
    ctx.insert(ContextPaths.CONFIG_LANDSCAPE, CONFIGURATION_MAPS.LANDSCAPE_CONFIGURATION_MAP)
    ctx.insert(ContextPaths.CONFIG_TOPOLOGY, CONFIGURATION_MAPS.TOPOLOGY_CONFIGURATION_MAP)
    ctx.insert(ContextPaths.CONFIG_RUNTIME, CONFIGURATION_MAPS.RUNTIME_CONFIGURATION_MAP)


    AM_CONFIG_VARIABLES.AM_CONFIG_DIRECTORY = os.path.join(AM_CONFIG_VARIABLES.AM_HOME_DIRECTORY, "config")
    if AM_CONFIG_VARNAMES.AM_CONFIG_DIRECTORY in environ:
        AM_CONFIG_VARIABLES.AM_CONFIG_DIRECTORY = environ[AM_CONFIG_VARNAMES.AM_CONFIG_DIRECTORY]
    ctx.insert(ContextPaths.PRESENCE_CONFIG_DIRECTORY, AM_CONFIG_VARIABLES.AM_CONFIG_DIRECTORY)


    if AM_CONFIG_VARNAMES.AM_CONFIG_STORAGE_URI in environ:
        AM_CONFIG_VARIABLES.AM_CONFIG_STORAGE_URI = environ[AM_CONFIG_VARNAMES.AM_CONFIG_STORAGE_URI]
    ctx.insert(ContextPaths.CONFIG_STORAGE_URI, AM_CONFIG_VARIABLES.AM_CONFIG_STORAGE_URI)

    # ====================== PROCESS CREDENTIAL VARIABLES ==============================

    if AM_CONFIG_VARNAMES.AM_CONFIG_CREDENTIAL_FILES in environ:
        AM_CONFIG_VARIABLES.AM_CONFIG_USE_CREDENTIALS = True
        AM_CONFIG_VARIABLES.AM_CONFIG_CREDENTIAL_FILES = split_and_normalize_path_list(
            environ[AM_CONFIG_VARNAMES.AM_CONFIG_CREDENTIAL_FILES])

    if AM_CONFIG_VARNAMES.AM_CONFIG_CREDENTIAL_NAMES in environ:
        AM_CONFIG_VARIABLES.AM_CONFIG_USE_CREDENTIALS = True
        AM_CONFIG_VARIABLES.AM_CONFIG_CREDENTIAL_NAMES = split_and_normalize_name_list(
            environ[AM_CONFIG_VARNAMES.AM_CONFIG_CREDENTIAL_NAMES])
    elif AM_CONFIG_DEFAULTS.AM_CONFIG_REQUIRE_CREDENTIALS and not AM_CONFIG_VARIABLES.AM_CONFIG_CREDENTIAL_FILES:
        AM_CONFIG_VARIABLES.AM_CONFIG_USE_CREDENTIALS = True
        AM_CONFIG_VARIABLES.AM_CONFIG_CREDENTIAL_NAMES = ["credentials"]

    if AM_CONFIG_VARNAMES.AM_CONFIG_CREDENTIAL_SOURCES in environ:
        AM_CONFIG_VARIABLES.AM_CONFIG_CREDENTIAL_SOURCES = split_and_normalize_source_list(
            environ[AM_CONFIG_VARNAMES.AM_CONFIG_CREDENTIAL_SOURCES])
    else:
        AM_CONFIG_VARIABLES.AM_CONFIG_CREDENTIAL_SOURCES = [os.path.join(AM_CONFIG_VARIABLES.AM_CONFIG_DIRECTORY)]

    # ====================== PROCESS LANDSCAPE VARIABLES ==============================

    if AM_CONFIG_VARNAMES.AM_CONFIG_LANDSCAPE_FILES in environ:
        AM_CONFIG_VARIABLES.AM_CONFIG_USE_LANDSCAPE = True
        AM_CONFIG_VARIABLES.AM_CONFIG_LANDSCAPE_FILES = split_and_normalize_path_list(
            environ[AM_CONFIG_VARNAMES.AM_CONFIG_LANDSCAPE_FILES])

    if AM_CONFIG_VARNAMES.AM_CONFIG_LANDSCAPE_NAMES in environ:
        AM_CONFIG_VARIABLES.AM_CONFIG_USE_LANDSCAPE = True
        AM_CONFIG_VARIABLES.AM_CONFIG_LANDSCAPE_NAMES = split_and_normalize_name_list(
            environ[AM_CONFIG_VARNAMES.AM_CONFIG_LANDSCAPE_NAMES])
    elif AM_CONFIG_DEFAULTS.AM_CONFIG_REQUIRE_LANDSCAPE and not AM_CONFIG_VARIABLES.AM_CONFIG_LANDSCAPE_FILES:
        AM_CONFIG_VARIABLES.AM_CONFIG_USE_LANDSCAPE = True
        AM_CONFIG_VARIABLES.AM_CONFIG_LANDSCAPE_NAMES = ["default-landscape"]

    if AM_CONFIG_VARNAMES.AM_CONFIG_LANDSCAPE_SOURCES in environ:
        AM_CONFIG_VARIABLES.AM_CONFIG_LANDSCAPE_SOURCES = split_and_normalize_source_list(
            environ[AM_CONFIG_VARNAMES.AM_CONFIG_LANDSCAPE_SOURCES])
    else:
        AM_CONFIG_VARIABLES.AM_CONFIG_LANDSCAPE_SOURCES = [os.path.join(
            AM_CONFIG_VARIABLES.AM_CONFIG_DIRECTORY, "landscapes")]

    # ====================== PROCESS RUNTIME VARIABLES ==============================

    if AM_CONFIG_VARNAMES.AM_CONFIG_RUNTIME_FILES in environ:
        AM_CONFIG_VARIABLES.AM_CONFIG_USE_RUNTIME = True
        AM_CONFIG_VARIABLES.AM_CONFIG_RUNTIME_FILES = split_and_normalize_path_list(
            environ[AM_CONFIG_VARNAMES.AM_CONFIG_RUNTIME_FILES])

    if AM_CONFIG_VARNAMES.AM_CONFIG_RUNTIME_NAMES in environ:
        AM_CONFIG_VARIABLES.AM_CONFIG_USE_RUNTIME = True
        AM_CONFIG_VARIABLES.AM_CONFIG_RUNTIME_NAMES = split_and_normalize_name_list(
            environ[AM_CONFIG_VARNAMES.AM_CONFIG_RUNTIME_NAMES])
    elif AM_CONFIG_DEFAULTS.AM_CONFIG_REQUIRE_RUNTIME and not AM_CONFIG_VARIABLES.AM_CONFIG_RUNTIME_FILES:
        AM_CONFIG_VARIABLES.AM_CONFIG_USE_RUNTIME = True
        AM_CONFIG_VARIABLES.AM_CONFIG_RUNTIME_NAMES = ["default-runtime"]

    if AM_CONFIG_VARNAMES.AM_CONFIG_RUNTIME_SOURCES in environ:
        AM_CONFIG_VARIABLES.AM_CONFIG_RUNTIME_SOURCES = split_and_normalize_source_list(
            environ[AM_CONFIG_VARNAMES.AM_CONFIG_RUNTIME_SOURCES])
    else:
        AM_CONFIG_VARIABLES.AM_CONFIG_RUNTIME_SOURCES = [os.path.join(
            AM_CONFIG_VARIABLES.AM_CONFIG_DIRECTORY, "runtimes")]

    # ====================== PROCESS TOPOLOGY VARIABLES ==============================

    if AM_CONFIG_VARNAMES.AM_CONFIG_TOPOLOGY_FILES in environ:
        AM_CONFIG_VARIABLES.AM_CONFIG_USE_TOPOLOGY = True
        AM_CONFIG_VARIABLES.AM_CONFIG_TOPOLOGY_FILES = split_and_normalize_path_list(
            environ[AM_CONFIG_VARNAMES.AM_CONFIG_TOPOLOGY_FILES])

    if AM_CONFIG_VARNAMES.AM_CONFIG_TOPOLOGY_NAMES in environ:
        AM_CONFIG_VARIABLES.AM_CONFIG_USE_TOPOLOGY = True
        AM_CONFIG_VARIABLES.AM_CONFIG_TOPOLOGY_NAMES = split_and_normalize_name_list(
            environ[AM_CONFIG_VARNAMES.AM_CONFIG_TOPOLOGY_NAMES])
    elif AM_CONFIG_DEFAULTS.AM_CONFIG_REQUIRE_RUNTIME and not AM_CONFIG_VARIABLES.AM_CONFIG_RUNTIME_FILES:
        AM_CONFIG_VARIABLES.AM_CONFIG_USE_RUNTIME = True
        AM_CONFIG_VARIABLES.AM_CONFIG_RUNTIME_NAMES = ["default-topology"]

    if AM_CONFIG_VARNAMES.AM_CONFIG_TOPOLOGY_SOURCES in environ:
        AM_CONFIG_VARIABLES.AM_CONFIG_TOPOLOGY_SOURCES = split_and_normalize_source_list(
            environ[AM_CONFIG_VARNAMES.AM_CONFIG_TOPOLOGY_SOURCES])
    else:
        AM_CONFIG_VARIABLES.AM_CONFIG_TOPOLOGY_SOURCES = [os.path.join(
            AM_CONFIG_VARIABLES.AM_CONFIG_DIRECTORY, "topologies")]

    return
